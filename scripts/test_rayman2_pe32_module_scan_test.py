"""Synthetic regression tests for exact-title PE32+ module scanner guard.

The private retail integration is opt-in via RAYMAN2_CD_EXE environment var.
No original game binaries are stored or generated by these tests.
"""
from __future__ import annotations

import hashlib
import os
from pathlib import Path
import struct
import subprocess
import sys
import tempfile
import unittest

from rayman2_pe32_module_scan_test import (
    EXPECTED_SHA, OLD, RETURN_VA, TARGET_VA, NEXT_VA,
    exact_file_offset, fixed_code, patch_bytes, relative_branch,
)


def synthetic_pe() -> bytes:
    b=bytearray(676352)
    b[:2]=b'MZ'
    struct.pack_into('<I',b,0x3c,0xb8)
    b[0xb8:0xbc]=b'PE\0\0'
    struct.pack_into('<HH',b,0xbc,0x14c,1)
    struct.pack_into('<H',b,0xb8+20,0xe0)
    opt=0xb8+24
    struct.pack_into('<H',b,opt,0x10b)
    struct.pack_into('<I',b,opt+28,0x400000)
    s=opt+0xe0
    b[s:s+8]=b'.text\0\0\0'
    struct.pack_into('<IIII',b,s+8,0x9a200,0x1000,0x9a200,0x400)
    struct.pack_into('<I',b,s+36,0x60000020)
    for va,chunk in (
        (TARGET_VA,OLD),
        (0x447c0c,bytes.fromhex('66 81 3A 4D 5A')),
        (0x447c18,bytes.fromhex('81 39 50 45 00 00')),
        (NEXT_VA,bytes.fromhex('8B 11 81 E2 DF DF DF DF')),
        (0x447c80,bytes.fromhex('55 8B EC 51 53')),
    ):
        fileoff=va-0x401000+0x400
        b[fileoff:fileoff+len(chunk)]=chunk
    return bytes(b)


class TestModuleScannerGuard(unittest.TestCase):
    def test_original_replacement_same_length(self):
        self.assertEqual(len(OLD),25)
        self.assertEqual(len(fixed_code()),25)
        self.assertNotEqual(OLD,fixed_code())
    def test_pe32_magic_and_offset(self):
        self.assertIn(bytes.fromhex('66 81 39 0B 01'),fixed_code())
        self.assertIn(bytes.fromhex('8B 49 60'),fixed_code())
    def test_pe32plus_rejected_with_new_jne(self):
        b=fixed_code()
        self.assertEqual(b[8],0x75)
        self.assertEqual(TARGET_VA+8+2+struct.unpack('b',b[9:10])[0],RETURN_VA)
    def test_missing_exports_early_return(self):
        b=fixed_code()
        self.assertEqual(b[15],0x74)
        self.assertEqual(TARGET_VA+15+2+struct.unpack('b',b[16:17])[0],RETURN_VA)
    def test_next_original_instruction_stays(self):
        self.assertEqual(TARGET_VA+len(fixed_code()),NEXT_VA)
    def test_out_of_range_branch(self):
        with self.assertRaisesRegex(ValueError,'outside int8'):
            relative_branch(0x1000,2,0x2000)
    def test_fixture_pe_mapping(self):
        b=synthetic_pe()
        self.assertEqual(exact_file_offset(b,TARGET_VA,25),0x47020)
        self.assertEqual(b[0x47020:0x47039],OLD)
    def test_fixture_patches_exactly_one_window(self):
        b=synthetic_pe()
        result=patch_bytes(b,hashlib.sha256(b).hexdigest())
        o=exact_file_offset(b,TARGET_VA,25)
        self.assertEqual(result[o:o+25],fixed_code())
        self.assertEqual(result[:o],b[:o])
        self.assertEqual(result[o+25:],b[o+25:])
    def test_wrong_sample_rejected(self):
        b=synthetic_pe()
        with self.assertRaisesRegex(ValueError,'SHA-256-verified'):
            patch_bytes(b)
    def test_truncated_input_rejected(self):
        with self.assertRaisesRegex(ValueError,'SHA-256-verified'):
            patch_bytes(synthetic_pe()[:-1])
    def test_tampered_scanner_detected(self):
        b=bytearray(synthetic_pe())
        o=exact_file_offset(b,TARGET_VA,25)
        b[o]^=0x20
        with self.assertRaisesRegex(ValueError,'scanner opcodes differ'):
            patch_bytes(bytes(b),hashlib.sha256(b).hexdigest())
    def test_tampered_neighbor_detected(self):
        b=bytearray(synthetic_pe())
        o=exact_file_offset(b,0x447c39,8)
        b[o]^=0x20
        with self.assertRaisesRegex(ValueError,'unexpected adjacent scanner'):
            patch_bytes(bytes(b),hashlib.sha256(b).hexdigest())
    def test_wrong_pe_kind_rejected(self):
        b=bytearray(synthetic_pe())
        nt=struct.unpack_from('<I',b,0x3c)[0]
        struct.pack_into('<H',b,nt+24,0x20b)
        with self.assertRaisesRegex(ValueError,'not a PE32'):
            exact_file_offset(b,TARGET_VA,25)
    def test_wrong_imagebase_rejected(self):
        b=bytearray(synthetic_pe())
        nt=struct.unpack_from('<I',b,0x3c)[0]
        struct.pack_into('<I',b,nt+24+28,0x500000)
        with self.assertRaisesRegex(ValueError,'unexpected executable PE geometry'):
            exact_file_offset(b,TARGET_VA,25)
    def test_wrong_section_flag_rejected(self):
        b=bytearray(synthetic_pe())
        struct.pack_into('<I',b,0xb8+24+0xe0+36,0xC0000040)
        with self.assertRaisesRegex(ValueError,'not executable'):
            exact_file_offset(b,TARGET_VA,25)
    def test_cli_cannot_overwrite(self):
        with tempfile.TemporaryDirectory() as td:
            source=Path(td)/'CD.exe'; output=Path(td)/'out.exe'
            source.write_bytes(synthetic_pe())
            output.write_bytes(b'preexisting')
            script=Path(__file__).with_name('rayman2_pe32_module_scan_test.py')
            run=subprocess.run([sys.executable,str(script),str(source),str(output)],capture_output=True,text=True)
            self.assertNotEqual(run.returncode,0)
            self.assertIn('output exists',run.stderr)
            self.assertEqual(output.read_bytes(),b'preexisting')
    @unittest.skipUnless(os.environ.get('RAYMAN2_CD_EXE'),'Private CD sample not supplied')
    def test_private_ret_orignal_hash(self):
        b=Path(os.environ['RAYMAN2_CD_EXE']).read_bytes()
        self.assertEqual(hashlib.sha256(b).hexdigest(),EXPECTED_SHA)
        result=patch_bytes(b)
        self.assertEqual(hashlib.sha256(result).hexdigest(),
                         'f32133d9add18b37adf47ce4b3e475b641b697e2b7db77cfe7b47063da468703')

if __name__=='__main__':
    unittest.main()
