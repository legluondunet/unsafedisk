#!/usr/bin/env python3
"""Narrow, unverified Rayman 2 DAT offset-subtraction experiment (V3).

Accepts ONLY the exact V2 executable already generated by the owner. Makes a
new copy with the original two-byte `sub [esi],ecx` at 0x44F133 neutralized.
Does not change the earlier indexed DAT-name substitution, any other I/O, or
original game resources. No commercial files included. Not a tested game fix.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import struct

INPUT_SHA256 = '35427161a5f9e109564aa00457640f4552497a6a40e28ede7a99a18f444eeb5d'
OUTPUT_SHA256 = '6df04e1c18d9318c9f8566a14018abc6f0e8dd84f7649eb4c411e81fabeb61f7'
INPUT_SIZE = 676352
SITE_VA = 0x44F133
OLD = bytes.fromhex('29 0E')  # sub dword ptr [esi],ecx
NEW = bytes.fromhex('90 90')  # 2 single-byte NOPs
PREVIOUS_VA = 0x44F12A
PREVIOUS_BYTES = bytes.fromhex('8B CB 57 0F AF CE 8B 75 08')
NEXT_VA = 0x44F135
NEXT_BYTES = bytes.fromhex('E8 C6 93 FF FF 8B 15 90 20 4A 00 90')


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def text_offset(data: bytes, va: int, length: int) -> int:
    """Map VA to a file-backed .text region of this exact 3-section PE32 layout."""
    if len(data) != INPUT_SIZE or data[:2] != b'MZ':
        raise ValueError('invalid MZ or file size')
    nt = struct.unpack_from('<I', data, 0x3c)[0]
    if nt > 4096 or data[nt:nt+4] != b'PE\0\0':
        raise ValueError('invalid PE signature')
    machine, count = struct.unpack_from('<HH', data, nt+4)
    opt_size = struct.unpack_from('<H', data, nt+20)[0]
    opt = nt+24
    if machine != 0x14c or count != 3 or opt_size < 0xe0 or opt+opt_size+40*count > len(data):
        raise ValueError('unexpected PE layout')
    if struct.unpack_from('<H', data, opt)[0] != 0x10b or struct.unpack_from('<I',data,opt+28)[0] != 0x400000:
        raise ValueError('unexpected image architecture or base')
    for i in range(count):
        p=opt+opt_size+40*i
        name=data[p:p+8].split(b'\0',1)[0]
        virtual_size,rva,raw_size,raw=struct.unpack_from('<IIII',data,p+8)
        if name != b'.text':
            continue
        relative=va-0x400000-rva
        if relative < 0 or relative+length > min(raw_size,virtual_size) or raw+relative+length > len(data):
            raise ValueError('site outside file-backed .text')
        return raw+relative
    raise ValueError('missing .text section')


def patch(data: bytes) -> tuple[bytes, dict]:
    if sha256(data) != INPUT_SHA256:
        raise ValueError('unknown source: requires exact Rayman2-portable-v2-test.exe SHA-256')
    pos=text_offset(data,SITE_VA,len(OLD))
    prior=text_offset(data,PREVIOUS_VA,len(PREVIOUS_BYTES))
    later=text_offset(data,NEXT_VA,len(NEXT_BYTES))
    if data[pos:pos+len(OLD)] != OLD:
        raise ValueError('DAT subtraction instruction anchor changed')
    if data[prior:prior+len(PREVIOUS_BYTES)] != PREVIOUS_BYTES:
        raise ValueError('earlier offset arithmetic changed')
    if data[later:later+len(NEXT_BYTES)] != NEXT_BYTES:
        raise ValueError('later call / fixed DAT selector changed')
    out=bytearray(data)
    out[pos:pos+len(OLD)] = NEW
    out=bytes(out)
    diff=[i for i,(a,b) in enumerate(zip(data,out)) if a != b]
    if diff != [pos,pos+1] or sha256(out) != OUTPUT_SHA256:
        raise ValueError('unexpected candidate bytes or SHA-256')
    report={
        'experiment':'V3: neutralize only 0x44F133 DAT offset subtraction',
        'source_sha256':sha256(data), 'output_sha256':sha256(out),
        'file_size':len(out), 'site_va':f'0x{SITE_VA:08X}',
        'changed_byte_count':len(diff),
        'previous_V2_DAT_selector_preserved':True,
        'original_512_byte_DAT_reads_preserved':True,
        'verified_under_Wine':False,
        'CD_independence_proven':False,
        'SafeDisc_decryption_proven':False,
    }
    return out,report


def main(argv=None) -> int:
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument('source',type=Path,help='exact V2 Rayman2-portable-v2-test.exe')
    ap.add_argument('output',type=Path,help='new executable filename; refuses overwrite')
    ap.add_argument('--dry-run',action='store_true',help='inspect without writing output')
    args=ap.parse_args(argv)
    if args.source.is_symlink() or not args.source.is_file():
        ap.error('source must be an existing regular file, not a symlink')
    if args.output.exists() or args.output.is_symlink() or args.output.resolve()==args.source.resolve():
        ap.error('refusing to overwrite or alter source')
    try:
        output,report=patch(args.source.read_bytes())
        if not args.dry_run:
            with args.output.open('xb') as f:
                f.write(output)
    except (ValueError,OSError) as e:
        ap.error(str(e))
    print(json.dumps(report,indent=2))
    print('Experimental only; do not replace the known working PE32 CD build.')
    return 0


if __name__=='__main__':
    raise SystemExit(main())
